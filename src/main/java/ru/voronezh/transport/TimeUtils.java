package ru.voronezh.transport;

/**
 * Вспомогательный бонус. класс для работы со временем суток.
 *
 * Принцип работы:
 * Все временные метки внутри системы для удобства вычислений переводятся
 * в одно число — "количество минут, прошедших с 00:00 (полуночи)".
 * Например:
 *   - 00:00 -> 0 минут
 *   - 01:30 -> 1*60 + 30 = 90 минут
 *   - 08:15 -> 8*60 + 15 = 495 минут
 *
 * Это позволяет легко складывать время в пути, сравнивать рейсы (раньше/позже)
 * и находить разницу (время ожидания или поездки), не работая со сложными датами.
 */
public final class TimeUtils {

    // Приватный конструктор запрещает создавать экземпляры бонус. класса
    private TimeUtils() {}

    /**
     * Преобразует число минут от полуночи обратно в привычный строковый формат ЧЧ:ММ.
     * общее число минут от начала суток (например, 510)
     * строка вида "08:30"
     */
    public static String timeToStr(int minutes) {
        // % 24 защищает от перехода через полночь
        int h = (minutes / 60) % 24;

        int m = minutes % 60;
        
        // %02d означает: вывести целое число минимум из 2 знаков с ведущим нулём (5 -> "05")
        return String.format("%02d:%02d", h, m);
    }

    /**
     * Преобразует строку времени "ЧЧ:ММ" в число минут от начала суток.
     */
    public static int strToTime(String timeStr) {
        // Разделяем строку по двоеточию на массив строк из двух элементов: ["08", "30"]
        String[] parts = timeStr.trim().split(":");
        if (parts.length != 2) {
            throw new IllegalArgumentException("Неверный формат времени: " + timeStr);
        }
        
        // Преобразуем строковые часы и минуты в целочисленные числа
        int h = Integer.parseInt(parts[0]);
        int m = Integer.parseInt(parts[1]);
        
        // 1 час = 60 минут, поэтому общее время = h * 60 + m
        return h * 60 + m;
    }
}
